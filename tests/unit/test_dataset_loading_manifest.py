"""Unit tests for CloudImageDataset.from_manifest_bundle (Phase 4, M4).

Covers consuming a split-manifest bundle (generated by split_generator, M3)
into a CloudImageDataset restricted to one subset. Uses a small synthetic
fixture with real tiny JPEGs (needed since __getitem__ actually decodes
images) and no duplicate groups, keeping these tests focused on subset
selection/consumption rather than re-testing M3's duplicate-atomicity logic.
"""
from pathlib import Path

import pytest
from PIL import Image

import split_generator as sg
import split_manifest as sm
import split_protocol as sp
from dataset_index import DatasetLoadingError
from dataset_loading import CloudImageDataset


def _make_image(path: Path, color: tuple[int, int, int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", (4, 4), color).save(path, "JPEG")


def _cfg() -> dict:
    return {
        "key": "synthetic_c",
        "official_split": False,
        "num_classes": 2,
        "class_map": {"alpha": "Alpha", "beta": "Beta"},
    }


def _inventory() -> dict:
    return {"dataset_key": "synthetic_c", "schema_version": 2, "duplicates": {"groups": []}}


def _protocol() -> sp.SplitProtocol:
    return sp.SplitProtocol(
        name="stratified_holdout_cv", version="1.0", test_fraction=0.2,
        canonical_seed=42, num_folds=5, variance_seeds=(7, 21, 42, 84, 168),
    )


def _build_fixture(root: Path, n_per_class: int = 20) -> None:
    for i in range(n_per_class):
        _make_image(root / "alpha" / f"a{i:03d}.jpg", (10, 20, 30))
    for i in range(n_per_class):
        _make_image(root / "beta" / f"b{i:03d}.jpg", (200, 210, 220))


def _bundle_and_inputs(tmp_path):
    _build_fixture(tmp_path)
    cfg, inv, proto = _cfg(), _inventory(), _protocol()
    bundle = sg.generate_split_manifests(cfg, tmp_path, inv, proto)
    return bundle, cfg, inv, proto


# --- permanent test / development pool loading ------------------------------- #
def test_from_manifest_bundle_test_subset(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    ds = CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")

    assert len(ds) == len(bundle["test"]["samples"])
    assert [p for p, _label in ds.index.samples] == sorted(bundle["test"]["samples"])
    image, label = ds[0]
    assert isinstance(image, Image.Image) and image.mode == "RGB"
    assert isinstance(label, int)


def test_from_manifest_bundle_dev_pool_subset(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    ds = CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="dev_pool")

    assert len(ds) == len(bundle["dev_pool"]["samples"])
    assert [p for p, _label in ds.index.samples] == sorted(bundle["dev_pool"]["samples"])


# --- fold training / validation subsets --------------------------------------- #
def test_from_manifest_bundle_cv_train_and_val_partition_dev_pool(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    seed = next(iter(bundle["cv"]))

    train_ds = CloudImageDataset.from_manifest_bundle(
        bundle, cfg, tmp_path, inv, proto, subset="cv_train", cv_seed=seed, fold=0
    )
    val_ds = CloudImageDataset.from_manifest_bundle(
        bundle, cfg, tmp_path, inv, proto, subset="cv_val", cv_seed=seed, fold=0
    )

    train_paths = {p for p, _label in train_ds.index.samples}
    val_paths = {p for p, _label in val_ds.index.samples}
    dev_paths = set(bundle["dev_pool"]["samples"])

    assert train_paths.isdisjoint(val_paths)
    assert train_paths | val_paths == dev_paths
    assert len(train_ds) + len(val_ds) == len(bundle["dev_pool"]["samples"])


def test_cv_fold_and_cv_val_subsets_are_identical(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    seed = next(iter(bundle["cv"]))

    fold_ds = CloudImageDataset.from_manifest_bundle(
        bundle, cfg, tmp_path, inv, proto, subset="cv_fold", cv_seed=seed, fold=1
    )
    val_ds = CloudImageDataset.from_manifest_bundle(
        bundle, cfg, tmp_path, inv, proto, subset="cv_val", cv_seed=seed, fold=1
    )
    assert fold_ds.index.samples == val_ds.index.samples


# --- deterministic ordering --------------------------------------------------- #
def test_from_manifest_bundle_ordering_is_deterministic(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    ds1 = CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")
    ds2 = CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")
    assert ds1.index.samples == ds2.index.samples
    assert ds1.index.samples == sorted(ds1.index.samples)


# --- metadata / label passthrough preserved ----------------------------------- #
def test_from_manifest_bundle_preserves_classes_and_labels(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    whole_ds = CloudImageDataset(cfg, tmp_path)
    subset_ds = CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")

    assert subset_ds.dataset_key == whole_ds.dataset_key
    assert subset_ds.classes == whole_ds.classes
    assert subset_ds.class_to_idx == whole_ds.class_to_idx
    assert subset_ds.class_display_names == whole_ds.class_display_names
    assert subset_ds.num_classes == whole_ds.num_classes

    whole_labels = dict(whole_ds.index.samples)
    for path, label in subset_ds.index.samples:
        assert label == whole_labels[path]  # label unchanged from the full dataset


# --- invalid design / bundle rejection ---------------------------------------- #
def test_from_manifest_bundle_rejects_invalid_bundle_schema(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    del bundle["cv"]
    with pytest.raises(sm.ManifestValidationError):
        CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")


def test_from_manifest_bundle_rejects_protocol_mismatch(tmp_path):
    bundle, cfg, inv, _proto = _bundle_and_inputs(tmp_path)
    wrong_protocol = sp.SplitProtocol(
        name="stratified_holdout_cv", version="9.9", test_fraction=0.2,
        canonical_seed=42, num_folds=5, variance_seeds=(42,),
    )
    with pytest.raises(sm.ManifestValidationError, match="expected"):
        CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, wrong_protocol, subset="test")


def test_from_manifest_bundle_rejects_official_split_dataset(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    cfg = dict(cfg)
    cfg["official_split"] = True
    with pytest.raises(DatasetLoadingError, match="official split"):
        CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="test")


# --- unsupported subset requests ---------------------------------------------- #
def test_from_manifest_bundle_rejects_unsupported_subset(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    with pytest.raises(DatasetLoadingError, match="Unsupported subset"):
        CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="not_a_real_subset")


def test_from_manifest_bundle_rejects_missing_fold_for_cv_subset(tmp_path):
    bundle, cfg, inv, proto = _bundle_and_inputs(tmp_path)
    with pytest.raises(DatasetLoadingError, match="requires both cv_seed and fold"):
        CloudImageDataset.from_manifest_bundle(bundle, cfg, tmp_path, inv, proto, subset="cv_train")


# --- interaction with existing DatasetIndex / M1-M2 behaviour ----------------- #
def test_whole_dataset_construction_is_unaffected_by_manifest_feature(tmp_path):
    _build_fixture(tmp_path, n_per_class=5)
    cfg = _cfg()
    ds = CloudImageDataset(cfg, tmp_path)
    assert len(ds) == 10
    assert ds.classes == ["alpha", "beta"]
